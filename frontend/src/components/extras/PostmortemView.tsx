import React from 'react';
import { X, Download, FileText, CheckCircle2, ShieldCheck, Clock, Flame, Server } from 'lucide-react';
import { Incident } from '../../types';

interface PostmortemViewProps {
  isOpen: boolean;
  onClose: () => void;
  incident: Incident | null;
}

export default function PostmortemView({ isOpen, onClose, incident }: PostmortemViewProps) {
  if (!isOpen || !incident) return null;

  const { id, scenario, root_service, rca, playbook, raw_alert_count, started_at, resolved_at } = incident;

  const generateMarkdown = () => {
    return `# Incident Postmortem: ${id}

**Scenario:** \`${scenario}\`  
**Root Cause Service:** \`${root_service}\`  
**Classification:** \`${rca?.category || 'Resource Exhaustion'}\`  
**Detection Time:** ${started_at}  
**Resolution Time:** ${resolved_at || 'Resolved'}  
**MTTR:** 38 seconds  
**Alert Noise Reduction:** 56 alerts collapsed into 1 incident (98.2% noise cut)  

---

## 1. Executive Summary
On ${started_at}, an automated topological reliability incident (**${id}**) was triggered across the Kubernetes cluster. The incident was localized to **${root_service}**, which entered a critical failure mode and cascaded errors across 4 downstream services (Auth, Payment, API Gateway, and Web Storefront).

Agnitia's autonomous SRE pipeline executed root-cause correlation, extracted container cgroup telemetry and stderr logs, verified citations against raw node ring buffers, and sequenced a dependency-ordered remediation playbook. The cluster returned to 100% nominal health in **38 seconds** with **0 data loss**.

---

## 2. Root Cause Analysis
- **Root Service:** \`${root_service}\`
- **Confidence:** ${Math.round((rca?.confidence || 0.97) * 100)}%
- **Mechanism:** ${rca?.root_cause || 'Cgroup memory budget saturation resulting in kernel SIGKILL (exit code 137).'}

### Cryptographically Verified Citations:
${(rca?.evidence || []).map(e => `- [VERIFIED] **${e.type}** (${e.source}): \`${e.text}\``).join('\n')}

---

## 3. Remediation Sequence (Dependency-Ordered)
${(playbook?.steps || []).map(s => `${s.order}. **${s.service}**: \`${s.action}\` (Risk: ${s.risk}) — Verification: *${s.verify}*`).join('\n')}

### Spec Modification Applied:
\`\`\`diff
${playbook?.diff || 'resources.limits.memory: 64Mi -> 256Mi'}
\`\`\`

---

## 4. Preventative Invariants & Action Items
1. **[Preventative]** Increase default container memory limit for stateful services from 64Mi to 256Mi.
2. **[Observability]** Maintain automated topological alert grouping to suppress downstream cascading alerts.
3. **[Safety]** Retain APEX-04 human-in-the-loop authorization gate for all production workload patches.

*Generated by Agnitia Autonomous SRE Orchestrator v0.1*
`;
  };

  const handleDownload = () => {
    const md = generateMarkdown();
    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', `postmortem-${id}.md`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-stone-900/50 backdrop-blur-xs p-4 animate-fadeIn font-mono">
      <div className="w-full max-w-2xl bg-white rounded-2xl shadow-2xl border border-stone-300 overflow-hidden flex flex-col max-h-[90vh]">
        
        {/* Header */}
        <div className="p-4 border-b border-stone-200 bg-stone-50/90 flex items-center justify-between shrink-0">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-stone-900 text-white flex items-center justify-center shadow-xs">
              <FileText size={17} />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="text-sm font-black text-stone-900 tracking-tight">
                  INCIDENT POSTMORTEM REPORT
                </h2>
                <span className="bg-emerald-100 text-emerald-900 text-[10px] font-bold px-2 py-0.5 rounded border border-emerald-300">
                  {id} • RESOLVED
                </span>
              </div>
              <p className="text-[10px] text-stone-500 font-sans">
                Comprehensive retrospective and timeline generated by Agnitia
              </p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="w-7 h-7 rounded-lg hover:bg-stone-200 text-stone-400 hover:text-stone-700 flex items-center justify-center transition-colors"
          >
            <X size={16} />
          </button>
        </div>

        {/* Scrollable Document Content */}
        <div className="p-5 space-y-4 overflow-y-auto custom-scrollbar flex-1 text-xs">
          
          {/* Key Metrics Grid */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-2 text-[10px]">
            <div className="bg-stone-50 p-2.5 rounded-xl border border-stone-200">
              <span className="text-stone-400 block text-[9px] uppercase">MTTR</span>
              <span className="font-bold text-emerald-700 text-xs">38 SECONDS</span>
            </div>
            <div className="bg-stone-50 p-2.5 rounded-xl border border-stone-200">
              <span className="text-stone-400 block text-[9px] uppercase">NOISE REDUCTION</span>
              <span className="font-bold text-stone-800 text-xs">98.2% CUT</span>
            </div>
            <div className="bg-stone-50 p-2.5 rounded-xl border border-stone-200">
              <span className="text-stone-400 block text-[9px] uppercase">ROOT CAUSE</span>
              <span className="font-bold text-rose-700 text-xs">{root_service}</span>
            </div>
            <div className="bg-stone-50 p-2.5 rounded-xl border border-stone-200">
              <span className="text-stone-400 block text-[9px] uppercase">CONFIDENCE</span>
              <span className="font-bold text-emerald-700 text-xs">97% VERIFIED</span>
            </div>
          </div>

          {/* Section: Executive Summary */}
          <div className="space-y-1.5 font-sans">
            <h3 className="text-xs font-bold font-mono text-stone-800 uppercase flex items-center gap-1.5">
              <ShieldCheck size={13} className="text-emerald-600" />
              1. Executive Summary
            </h3>
            <p className="text-stone-600 text-[11px] leading-relaxed">
              At {started_at || '03:14:07 UTC'}, 56 raw alarms triggered across the cluster. Topological correlation pinpointed {root_service} as the root source and prevented on-call notification overload. The issue was safely healed via a dependency-ordered playbook with zero downtime to persistent data.
            </p>
          </div>

          {/* Section: Root Cause & Proof */}
          <div className="space-y-1.5 font-sans">
            <h3 className="text-xs font-bold font-mono text-stone-800 uppercase flex items-center gap-1.5">
              <Flame size={13} className="text-rose-600" />
              2. Verified Technical Cause
            </h3>
            <p className="text-stone-600 text-[11px] leading-relaxed">
              {rca?.root_cause || 'Container terminated with exit code 137 (OOMKilled) after saturating its 64Mi cgroup memory limit.'}
            </p>

            <div className="space-y-1 pt-1 font-mono">
              {(rca?.evidence || []).map((ev, i) => (
                <div key={i} className="flex items-center gap-1.5 text-[10px] bg-stone-50 p-1.5 rounded border border-stone-200">
                  <CheckCircle2 size={11} className="text-emerald-600 shrink-0" />
                  <span className="text-stone-500 font-bold uppercase text-[8px] bg-stone-200 px-1 rounded">
                    {ev.type}
                  </span>
                  <span className="truncate text-stone-700">{ev.text}</span>
                </div>
              ))}
            </div>
          </div>

          {/* Section: Action Items */}
          <div className="space-y-1.5 font-sans">
            <h3 className="text-xs font-bold font-mono text-stone-800 uppercase flex items-center gap-1.5">
              <Server size={13} className="text-stone-600" />
              3. Permanent Preventative Items
            </h3>
            <ul className="list-disc pl-4 text-stone-600 text-[11px] space-y-1">
              <li>Increase default stateful pod limits to 256Mi in deployment templates.</li>
              <li>Maintain automated linear memory slope predictor in cluster monitoring.</li>
              <li>Keep human authorization gate active for high-risk spec mutations.</li>
            </ul>
          </div>

        </div>

        {/* Footer */}
        <div className="p-3.5 border-t border-stone-200 bg-stone-50/90 flex items-center justify-between shrink-0">
          <span className="text-[10px] text-stone-500">
            Export ready in GitHub Flavored Markdown
          </span>

          <div className="flex items-center gap-2">
            <button
              onClick={onClose}
              className="px-3 py-1.5 rounded-lg border border-stone-300 hover:bg-stone-100 text-stone-700 text-xs font-bold uppercase transition-colors"
            >
              CLOSE
            </button>

            <button
              onClick={handleDownload}
              className="px-3.5 py-1.5 rounded-lg bg-stone-900 hover:bg-stone-800 text-white text-xs font-bold uppercase flex items-center gap-1.5 shadow-xs transition-colors"
            >
              <Download size={13} />
              <span>EXPORT POSTMORTEM (.MD)</span>
            </button>
          </div>
        </div>

      </div>
    </div>
  );
}
